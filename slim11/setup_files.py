"""Files injected into the image: autounattend.xml and the specialize script.

Instead of editing registry hives offline (which needs Windows' reg.exe or a
native hive library), Slim11 hands the changes to Windows Setup. The answer
file sets the hardware-check bypass inside WinPE, and a PowerShell script runs
in the specialize pass, as SYSTEM, before the first user is created. That keeps
the builder itself identical on Linux, macOS and Windows.
"""

from __future__ import annotations

from xml.sax.saxutils import escape

from .catalog import HKCU, HKLM, RegValue, Selection

# Where the script lives inside the install image and on the installed system.
SCRIPT_DIR_IN_IMAGE = "/Windows/Setup/Scripts/Slim11"
SCRIPT_DIR_ON_TARGET = r"C:\Windows\Setup\Scripts\Slim11"
SCRIPT_NAME = "Specialize.ps1"

_ARCH = {"x64": "amd64", "x86_64": "amd64", "amd64": "amd64", "arm64": "arm64", "aarch64": "arm64", "x86": "x86"}


def unattend_arch(architecture: str) -> str:
    try:
        return _ARCH[architecture.lower()]
    except KeyError:
        raise ValueError(f"Unsupported image architecture: {architecture}") from None


def _ps_quote(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def _reg_add(root: str, value: RegValue) -> str:
    data = str(value.value)
    return (f"reg.exe add {_cmd_quote(root + chr(92) + value.key)} /v {_cmd_quote(value.name)} "
            f"/t {value.kind} /d {_cmd_quote(data)} /f")


def _cmd_quote(text: str) -> str:
    if '"' in text:
        raise ValueError(f"Double quotes are not allowed in registry data: {text}")
    return f'"{text}"'


def specialize_script(selection: Selection) -> str:
    """PowerShell run once by Setup during the specialize pass."""
    tweaks = selection.chosen_tweaks()
    machine = [v for t in tweaks for v in t.values if v.hive == HKLM]
    user = [v for t in tweaks for v in t.values if v.hive == HKCU]
    tasks = [task for t in tweaks for task in t.tasks_to_disable]
    packages = selection.packages()

    lines = [
        "# Generated by Slim11 Builder. Runs once during Windows Setup (specialize pass).",
        "$ErrorActionPreference = 'Continue'",
        f"$log = Join-Path {_ps_quote(SCRIPT_DIR_ON_TARGET)} 'Specialize.log'",
        "Start-Transcript -Path $log -Append | Out-Null",
        "",
    ]
    if packages:
        lines += [
            "$remove = @(",
            *[f"  {_ps_quote(p)}" for p in packages],
            ")",
            "Get-AppxProvisionedPackage -Online | Where-Object {",
            "  $name = $_.DisplayName",
            "  $remove | Where-Object { $name -like \"$_*\" }",
            "} | ForEach-Object {",
            "  $pkg = $_.PackageName",
            "  Write-Output \"Removing $pkg\"",
            "  try { Remove-AppxProvisionedPackage -Online -PackageName $pkg -ErrorAction Stop | Out-Null }",
            "  catch { Write-Warning \"Could not remove ${pkg}: $_\" }",
            "}",
            "",
        ]
    if machine:
        lines += [_reg_add("HKLM", v) for v in machine] + [""]
    if user:
        lines += [
            r"reg.exe load 'HKU\Slim11Default' 'C:\Users\Default\NTUSER.DAT' | Out-Null",
            *[_reg_add(r"HKU\Slim11Default", v) for v in user],
            "[gc]::Collect()",
            r"reg.exe unload 'HKU\Slim11Default' | Out-Null",
            "",
        ]
    if tasks:
        # Task names differ between Windows builds; skip the ones this build lacks
        # instead of logging schtasks errors for them.
        lines += [
            "$tasks = @(",
            *[f"  {_ps_quote(t)}" for t in tasks],
            ")",
            "foreach ($task in $tasks) {",
            "  $path = $task.Substring(0, $task.LastIndexOf('\\') + 1)",
            "  $name = $task.Substring($task.LastIndexOf('\\') + 1)",
            "  $found = Get-ScheduledTask -TaskPath $path -TaskName $name -ErrorAction SilentlyContinue",
            "  if ($found) { $found | Disable-ScheduledTask | Out-Null; Write-Output \"Disabled task $task\" }",
            "}",
        ]
    lines += ["", "Stop-Transcript | Out-Null", ""]
    return "\r\n".join(lines)


def autounattend(selection: Selection, architecture: str, *, compact: bool = False) -> str:
    """Answer file placed at the root of the ISO."""
    arch = unattend_arch(architecture)
    tweak_ids = set(selection.tweaks)
    setup_values = [v for t in selection.chosen_tweaks() for v in t.setup_values]

    def component(name: str, body: str) -> str:
        return (f'    <component name="{name}" processorArchitecture="{arch}" '
                'publicKeyToken="31bf3856ad364e35" language="neutral" versionScope="nonSxS">\n'
                f"{body}    </component>\n")

    def run_sync(commands: list[str], element: str = "RunSynchronousCommand") -> str:
        out = '      <RunSynchronous>\n'
        for order, command in enumerate(commands, start=1):
            out += (f'        <{element} wcm:action="add">\n'
                    f"          <Order>{order}</Order>\n"
                    f"          <Path>{escape(command)}</Path>\n"
                    f"        </{element}>\n")
        return out + "      </RunSynchronous>\n"

    pe_body = (
        "      <DynamicUpdate><Enable>false</Enable><WillShowUI>OnError</WillShowUI></DynamicUpdate>\n"
        "      <ImageInstall><OSImage>\n"
        f"        <Compact>{'true' if compact else 'false'}</Compact>\n"
        "        <WillShowUI>OnError</WillShowUI>\n"
        "        <InstallFrom><MetaData wcm:action=\"add\"><Key>/IMAGE/INDEX</Key><Value>1</Value></MetaData></InstallFrom>\n"
        "      </OSImage></ImageInstall>\n"
    )
    if setup_values:
        pe_body += run_sync([_reg_add("HKLM", v).replace("reg.exe", "reg", 1) for v in setup_values])

    script = f"{SCRIPT_DIR_ON_TARGET}\\{SCRIPT_NAME}"
    specialize = run_sync(
        [f'powershell.exe -NoProfile -ExecutionPolicy Bypass -File "{script}"'],
        element="RunSynchronousCommand",
    )

    oobe = "      <OOBE>\n        <HideEULAPage>false</HideEULAPage>\n        <HideOEMRegistrationScreen>true</HideOEMRegistrationScreen>\n"
    if "local-account" in tweak_ids:
        oobe += "        <HideOnlineAccountScreens>true</HideOnlineAccountScreens>\n"
    oobe += "      </OOBE>\n"

    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by Slim11 Builder -->\n'
        '<unattend xmlns="urn:schemas-microsoft-com:unattend" '
        'xmlns:wcm="http://schemas.microsoft.com/WMIConfig/2002/State">\n'
        '  <settings pass="windowsPE">\n'
        + component("Microsoft-Windows-Setup", pe_body)
        + '  </settings>\n'
        '  <settings pass="specialize">\n'
        + component("Microsoft-Windows-Deployment", specialize)
        + '  </settings>\n'
        '  <settings pass="oobeSystem">\n'
        + component("Microsoft-Windows-Shell-Setup", oobe)
        + '  </settings>\n'
        '</unattend>\n'
    )
